package Core.Oops.Encapsulation.Person;

public class Person {
    private String name;
    private long mno;

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public long getMno() {
        return mno;
    }

    public void setMno(long mno) {
        this.mno = mno;
    }
}
